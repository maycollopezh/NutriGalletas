-- Contextos Auth simulados en SQL. Todos los cambios se revierten.
begin;
create temporary table resultado_iop(comprobaciones integer, resultado text);
do $$
declare a uuid; w uuid; c uuid; sa uuid:=gen_random_uuid(); sw uuid:=gen_random_uuid(); sc uuid:=gen_random_uuid();
  p uuid; supplier uuid; n integer; checks integer:=0; denied boolean; j jsonb;
begin
  select id into strict a from public.perfiles_usuarios where rol='administrador' and activo order by id limit 1;
  select id into strict w from public.perfiles_usuarios where rol='almacen' and activo order by id limit 1;
  select id into strict c from public.perfiles_usuarios where rol='cajero' and activo order by id limit 1;
  perform public.autorizar_sesion(sa,a); perform public.autorizar_sesion(sw,w); perform public.autorizar_sesion(sc,c);
  select id into strict p from public.productos where codigo='GAL-001';
  select id into strict supplier from public.proveedores where activo order by id limit 1;
  if not (select relrowsecurity from pg_class where oid='public.parametros_inventario'::regclass) then raise exception 'Falta RLS'; end if; checks:=checks+1;
  perform set_config('request.jwt.claim.sub',a::text,true);
  perform set_config('request.jwt.claims',jsonb_build_object('sub',a,'session_id',sa)::text,true);
  execute 'set local role authenticated';
  select count(*) into n from public.parametros_inventario; if n<6 then raise exception 'Faltan parámetros iniciales'; end if; checks:=checks+1;
  update public.parametros_inventario set unidades_en_camino=10 where producto_id=p;
  get diagnostics n=row_count; if n<>1 then raise exception 'Administrador no edita'; end if; checks:=checks+1;
  denied:=false; begin update public.parametros_inventario set costo_mantenimiento_anual=0 where producto_id=p; exception when check_violation then denied:=true; end;
  if not denied then raise exception 'Aceptó costo cero'; end if; checks:=checks+1;
  denied:=false; begin update public.parametros_inventario set seguridad_metodo='estadistico',demanda_fuente='manual' where producto_id=p; exception when check_violation then denied:=true; end;
  if not denied then raise exception 'Aceptó modelo estadístico sin historial'; end if; checks:=checks+1;
  j:=public.consultar_demanda_inventario();
  if jsonb_typeof(j)<>'array' then raise exception 'Agregación inválida'; end if;
  if exists(select 1 from jsonb_array_elements(j) e where not(e ? 'fecha' and e ? 'producto_id' and e ? 'cantidad') or (select count(*) from jsonb_object_keys(e))<>3) then raise exception 'Datos extra en agregación'; end if; checks:=checks+1;
  execute 'reset role';
  perform set_config('request.jwt.claim.sub',w::text,true);
  perform set_config('request.jwt.claims',jsonb_build_object('sub',w,'session_id',sw)::text,true);
  execute 'set local role authenticated';
  select count(*) into n from public.parametros_inventario; if n<6 then raise exception 'Almacén sin parámetros'; end if; checks:=checks+1;
  update public.parametros_inventario set costo_pedido=1; get diagnostics n=row_count;
  if n<>0 then raise exception 'Almacén editó parámetros'; end if; checks:=checks+1;
  perform public.consultar_demanda_inventario(); checks:=checks+1;
  select count(*) into n from public.ventas; if n<>0 then raise exception 'Almacén ve ventas'; end if; checks:=checks+1;
  perform public.registrar_compra(jsonb_build_object('producto_id',p,'proveedor_id',supplier,'cantidad',3,'costo_unitario',4,'fecha_vencimiento','2099-01-01','codigo_lote','QA-IOP-'||sw::text));
  select unidades_en_camino into n from public.parametros_inventario where producto_id=p;
  if n<>7 then raise exception 'Recepción no descontó pendientes'; end if; checks:=checks+1;
  denied:=false; begin perform public.registrar_compra(jsonb_build_object('producto_id',p,'proveedor_id',supplier,'cantidad',3,'costo_unitario',4,'fecha_vencimiento','2099-01-01','codigo_lote','QA-IOP-'||sw::text)); exception when unique_violation then denied:=true; end;
  select unidades_en_camino into n from public.parametros_inventario where producto_id=p;
  if not denied or n<>7 then raise exception 'Compra rechazada alteró pendientes'; end if; checks:=checks+1;
  execute 'reset role';
  perform set_config('request.jwt.claim.sub',c::text,true);
  perform set_config('request.jwt.claims',jsonb_build_object('sub',c,'session_id',sc)::text,true);
  execute 'set local role authenticated';
  select count(*) into n from public.parametros_inventario; if n<>0 then raise exception 'Cajero ve parámetros'; end if; checks:=checks+1;
  denied:=false; begin perform public.consultar_demanda_inventario(); exception when raise_exception then denied:=true; end;
  if not denied then raise exception 'Cajero consultó agregados'; end if; checks:=checks+1;
  execute 'reset role';
  perform set_config('request.jwt.claims',jsonb_build_object('sub',a,'session_id',gen_random_uuid())::text,true);
  perform set_config('request.jwt.claim.sub',a::text,true);
  execute 'set local role authenticated';
  denied:=false; begin perform public.consultar_demanda_inventario(); exception when raise_exception then denied:=true; end;
  if not denied then raise exception 'Sesión sin autorización consultó agregados'; end if; checks:=checks+1;
  execute 'reset role'; execute 'set local role anon';
  denied:=false; begin perform public.consultar_demanda_inventario(); exception when insufficient_privilege then denied:=true; end;
  if not denied then raise exception 'Anónimo consultó agregados'; end if; checks:=checks+1;
  execute 'reset role';
  insert into resultado_iop values(checks,'Correctas. Pruebas con identidades SQL simuladas. Sin cambios persistentes.');
end $$;
select * from resultado_iop;
rollback;
